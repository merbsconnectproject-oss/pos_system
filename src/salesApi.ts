import { request } from './apiClient';
import type { CartItem, CompletedSale, PaymentEntry, Product } from './types';

/**
 * Selling — FR-POS, FR-PAY.
 *
 * BR-11: the wire carries pesewas as integers. Major units exist only for
 * display, and converting at the boundary is what stops a fraction of a pesewa
 * ever reaching the arithmetic.
 */
const toPesewas = (major: number) => Math.round(major * 100);
const toMajor = (pesewas: number) => pesewas / 100;

export interface SaleWire {
  id: string;
  receiptNumber: string;
  outletId: string;
  terminalId?: string | null;
  cashierName: string;
  customerId?: string | null;
  customerName?: string | null;
  customerPhone?: string | null;
  subtotal: number;
  discountTotal: number;
  total: number;
  changeDue: number;
  status: 'COMPLETED' | 'VOIDED';
  voidReason?: string | null;
  voidedBy?: string | null;
  voidedAt?: string | null;
  createdAt: string;
  items: {
    productId: string; productName: string; sku: string; selectedUnit: string;
    conversionFactor: number; quantity: number; quantityBase: number;
    unitPrice: number; discount: number; lineTotal: number;
    frozenCostPrice: number; belowFloor: boolean;
  }[];
  payments: { id: string; method: PaymentEntry['method']; amount: number; provider?: string | null; reference?: string | null }[];
}

/**
 * The server's sale, folded back onto the app's shape.
 *
 * `cart` is passed in because the wire carries product ids while `CompletedSale`
 * carries whole products — the receipt needs the line as the cashier rang it up,
 * and re-deriving that from the catalogue would show today's price rather than
 * the one that was charged.
 */
export const toCompletedSale = (wire: SaleWire, cart: CartItem[], outletName: string): CompletedSale => ({
  id: wire.id,
  receiptNumber: wire.receiptNumber,
  outletId: wire.outletId,
  outletName,
  terminalId: wire.terminalId || '01',
  cashierName: wire.cashierName,
  customerId: wire.customerId || undefined,
  customerName: wire.customerName || 'Walk-in Customer',
  customerPhone: wire.customerPhone || undefined,
  customerType: 'retail',
  items: cart,
  subtotal: toMajor(wire.subtotal),
  discountTotal: toMajor(wire.discountTotal),
  total: toMajor(wire.total),
  payments: wire.payments.map((payment) => ({
    method: payment.method,
    amount: toMajor(payment.amount),
    provider: (payment.provider as PaymentEntry['provider']) || undefined,
    reference: payment.reference || undefined,
    verified: payment.method !== 'cash' ? true : undefined,
  })),
  changeDue: toMajor(wire.changeDue),
  createdAt: new Date(wire.createdAt).toLocaleDateString('en-GB') + ' '
    + new Date(wire.createdAt).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' }),
  status: wire.status,
  voidReason: wire.voidReason || undefined,
  voidedBy: wire.voidedBy || undefined,
  voidedAt: wire.voidedAt || undefined,
});

export interface SaleDraft {
  /** BR-7: generated by the client. The same id twice records one sale. */
  id: string;
  outletId: string;
  terminalId?: string;
  customerId?: string;
  customerName?: string;
  customerPhone?: string;
  cart: CartItem[];
  payments: PaymentEntry[];
}

/**
 * Rebuild the cart lines of a sale fetched from history.
 *
 * The wire carries product ids; `CompletedSale` carries whole products, because
 * the receipt reprints the line as it was rung up. Prices come from the sale,
 * never from the catalogue — a product repriced since is still owed the receipt
 * it was sold at, which is BR-5 applied to what the customer sees.
 *
 * A product deleted from the catalogue still has to render, so its name and SKU
 * are taken from the sale line itself.
 */
export const cartFromWire = (wire: SaleWire, catalogue: Product[]): CartItem[] => {
  const byId = new Map(catalogue.map((product) => [product.id, product]));

  return wire.items.map((line) => {
    const known = byId.get(line.productId);
    const product: Product = known ?? {
      id: line.productId,
      name: line.productName,
      sku: line.sku,
      category: 'Hardware & Tools',
      brand: '',
      barcodes: [],
      baseUnit: line.selectedUnit as Product['baseUnit'],
      retailPrice: line.unitPrice,
      tradePrice: line.unitPrice,
      floorPrice: line.unitPrice,
      costPrice: {},
      stock: {},
      minStockAlert: {},
      imageUrl: '',
      active: false,
    };

    return {
      product,
      quantity: line.quantity,
      selectedUnit: line.selectedUnit,
      conversionFactor: line.conversionFactor,
      unitPrice: line.unitPrice,
      // BR-5: the cost as it was at the moment of sale, so a reprinted
      // receipt and a past margin both stay true after stock is repriced.
      frozenCostPrice: line.frozenCostPrice,
      discount: toMajor(line.discount),
      lineTotal: toMajor(line.lineTotal),
      floorPriceApproved: line.belowFloor || undefined,
    };
  });
};

export const salesApi = {
  complete: (draft: SaleDraft) => request<SaleWire>('/api/sales', {
    method: 'POST',
    body: JSON.stringify({
      id: draft.id,
      outletId: draft.outletId,
      terminalId: draft.terminalId,
      customerId: draft.customerId,
      customerName: draft.customerName,
      customerPhone: draft.customerPhone,
      // Line totals are deliberately not sent. The server prices the sale from
      // the catalogue, so a receipt cannot say whatever the browser computed.
      items: draft.cart.map((item) => ({
        productId: item.product.id,
        selectedUnit: item.selectedUnit,
        conversionFactor: item.conversionFactor,
        quantity: item.quantity,
        unitPrice: item.unitPrice,
        discount: toPesewas(item.discount || 0),
        floorApprovedBy: item.floorPriceApprover || undefined,
      })),
      payments: draft.payments.map((payment) => ({
        id: crypto.randomUUID(),
        method: payment.method,
        amount: toPesewas(payment.amount),
        provider: payment.provider,
        reference: payment.reference,
      })),
    }),
  }),

  /** BR-3 · FR-POS-19. */
  voidSale: (saleId: string, reason: string) =>
    request<SaleWire>(`/api/sales/${encodeURIComponent(saleId)}/void`, {
      method: 'POST', body: JSON.stringify({ reason }),
    }),

  recent: (outletId?: string, query?: string, limit = 100) => {
    const parameters = new URLSearchParams({ limit: String(limit) });
    if (outletId) parameters.set('outletId', outletId);
    if (query) parameters.set('q', query);
    return request<SaleWire[]>(`/api/sales?${parameters}`);
  },
};

export const terminalsApi = {
  /** BR-6: the till whose block the receipt number comes from. */
  atOutlet: (outletId: string) =>
    request<{ id: string; code: string; name: string; remaining: number }[]>(
      `/api/terminals?outletId=${encodeURIComponent(outletId)}`),
};
