/**
 * Test vector generator — run with `npm run gen:vectors`.
 *
 * Emits `docs/contract/test-vectors.json`, the single file that both
 * implementations of the domain rules are tested against:
 *
 *     src/contract-check.ts          (frontend, TypeScript)  npm run check
 *     pos-api RulesVectorTest.java   (backend, Java)         ./mvnw test
 *
 * Vectors are GENERATED from the frontend rules, never hand-written, so the
 * expected values cannot drift from the implementation that produces them.
 * If a vector needs to change, change the rule and regenerate — then both
 * suites fail together until they agree.
 *
 * Decimal values are emitted as STRINGS. Java must build them with
 * `new BigDecimal("1.005")`, which is exact; `BigDecimal.valueOf(double)`
 * would re-introduce the binary float error this file exists to pin down.
 */
import { writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { roundMoney, toPesewas, fromPesewas, lineTotal, sumMoney, roundQuantity } from './money';
import { weightedAverageCost, costPerBaseUnit } from './stockCosting';
import { createBlock, formatReceiptNumber, issueReceiptNumber } from './receiptSequence';
import { DEFAULT_ROLE_PERMISSIONS, resolvePermissions, PERMISSION_CODES } from './permissions';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, '../docs/contract/test-vectors.json');

/**
 * The Java suite reads its own copy from the classpath, so both are written
 * here. Copying by hand is a step somebody forgets, and the failure mode is the
 * worst kind: two suites asserting different contracts, both green.
 */
const OUT_API = resolve(here, '../../pos-api/src/test/resources/test-vectors.json');

/** Fixed 2dp string, so Java reads an exact decimal rather than a double. */
const money = (n: number) => n.toFixed(2);
/** Fixed 3dp string — BR-12 quantities. */
const qty = (n: number) => n.toFixed(3);

// --- BR-11 money -----------------------------------------------------------
// Boundary cases chosen to catch binary-float drift between the two runtimes.
const ROUND_INPUTS = [
  0, 0.004, 0.005, 0.125, 0.145, 1.005, 1.115, 2.675, 8.615, 10.005,
  18.5, 55.005, 1234.565, 99.994, 99.995,
  -0.005, -1.005, -0.145, -18.5,
];

const LINE_INPUTS: Array<[number, number, number]> = [
  [3, 18.335, 0],
  [1, 0.125, 0],
  [2, 0.125, 0],
  [12.5, 4.2, 0],
  [287.5, 3.75, 10],
  [1, 100, 0.005],
  [3, 33.333, 0],
];

const SUM_INPUTS: number[][] = [
  [0.125, 0.125],
  [1.005, 1.005],
  [18.5, 4.25, 0.3],
  [],
  [99.99, 0.01],
];

// --- BR-4 weighted average cost -------------------------------------------
const WAC_INPUTS: Array<[number, number, number, number]> = [
  // onHand, currentAverage, receivedBase, unitCostPerBase
  [0, 0, 300, 4.5],        // first receipt sets the average
  [300, 4.5, 300, 5.5],    // even blend
  [287.5, 4.5, 100, 6.0],  // after a cut-length sale
  [100, 10, 100, 20],
  [0, 0, 0, 7.25],         // nothing on hand, nothing received
  [150, 3.333, 75, 4.777],
];

const CPB_INPUTS: Array<[number, number]> = [
  [450, 100],   // a 100 m drum costing 450
  [120, 12],    // a carton of 12
  [50, 0],      // guard: factor 0 falls back to the unit cost
  [99.99, 3],
];

// --- BR-6 receipt numbers --------------------------------------------------
const RECEIPT_INPUTS: Array<[string, string, number]> = [
  ['INC', '01', 4312],
  ['INC', '01', 1],
  ['RAD', '02', 999999],
  ['RAD', '01', 1000],
];

const vectors = {
  $comment:
    'GENERATED by `npm run gen:vectors` from the frontend rules. Do not hand-edit. ' +
    'Read by src/contract-check.ts and by pos-api RulesVectorTest.java. ' +
    'Decimals are strings: build them with new BigDecimal("...") in Java.',
  generatedAt: new Date().toISOString().slice(0, 10),

  money: {
    rule: 'BR-11',
    roundMoney: ROUND_INPUTS.map((input) => ({
      in: String(input),
      out: money(roundMoney(input)),
    })),
    toPesewas: ROUND_INPUTS.map((input) => ({
      in: String(input),
      out: toPesewas(input),
    })),
    fromPesewas: [1850, 1, 0, -1850, 101, 100].map((input) => ({
      in: input,
      out: money(fromPesewas(input)),
    })),
    lineTotal: LINE_INPUTS.map(([quantity, unitPrice, discount]) => ({
      quantity: qty(quantity),
      unitPrice: String(unitPrice),
      discount: String(discount),
      out: money(lineTotal(quantity, unitPrice, discount)),
    })),
    sumMoney: SUM_INPUTS.map((values) => ({
      in: values.map(String),
      out: money(sumMoney(values)),
    })),
  },

  quantity: {
    rule: 'BR-12',
    roundQuantity: [287.5, 12.3455, 12.3454, 0.0005, 100, 0.001, -12.3455].map((input) => ({
      in: String(input),
      out: qty(roundQuantity(input)),
    })),
  },

  weightedAverageCost: {
    rule: 'BR-4',
    cases: WAC_INPUTS.map(([onHand, currentAverage, receivedBase, unitCostPerBase]) => ({
      quantityOnHand: qty(onHand),
      currentAverage: money(currentAverage),
      quantityReceivedBase: qty(receivedBase),
      unitCostPerBase: money(unitCostPerBase),
      out: money(weightedAverageCost(onHand, currentAverage, receivedBase, unitCostPerBase)),
    })),
  },

  costPerBaseUnit: {
    rule: 'FR-UOM-05',
    cases: CPB_INPUTS.map(([purchaseUnitCost, conversionFactor]) => ({
      purchaseUnitCost: money(purchaseUnitCost),
      conversionFactor: String(conversionFactor),
      out: money(roundMoney(costPerBaseUnit(purchaseUnitCost, conversionFactor))),
    })),
  },

  receiptNumber: {
    rule: 'BR-6',
    format: '{OUTLET}-{TERMINAL}-{SEQ padded to 6}',
    cases: RECEIPT_INPUTS.map(([outletPrefix, terminalCode, sequence]) => ({
      outletPrefix,
      terminalCode,
      sequence,
      out: formatReceiptNumber(createBlock(outletPrefix, terminalCode, sequence), sequence),
    })),
    blockExhaustion: (() => {
      // A block of 2 issues exactly two numbers, then refuses.
      let block = createBlock('INC', '01', 500, 2);
      const issued: string[] = [];
      for (let i = 0; i < 2; i++) {
        const next = issueReceiptNumber(block);
        issued.push(next.receiptNumber);
        block = next.block;
      }
      let refused = false;
      try {
        issueReceiptNumber(block);
      } catch {
        refused = true;
      }
      return { start: 500, size: 2, issued, thirdCallRefused: refused };
    })(),
  },

  permissions: {
    rule: 'PRD §6',
    allCodes: [...PERMISSION_CODES],
    roles: Object.fromEntries(
      Object.entries(DEFAULT_ROLE_PERMISSIONS).map(([role, codes]) => [
        role,
        [...resolvePermissions(codes).codes].sort(),
      ]),
    ),
    overrides: [
      {
        baseRole: 'cashier',
        override: { 'sale.void': true },
        grants: 'sale.void',
        expected: resolvePermissions(DEFAULT_ROLE_PERMISSIONS.cashier, { 'sale.void': true }).has('sale.void'),
      },
      {
        baseRole: 'manager',
        override: { 'sale.void': false },
        grants: 'sale.void',
        expected: resolvePermissions(DEFAULT_ROLE_PERMISSIONS.manager, { 'sale.void': false }).has('sale.void'),
      },
    ],
  },
};

const serialised = JSON.stringify(vectors, null, 2) + '\n';

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, serialised, 'utf8');

// The backend is a separate repository. Its copy is written when it happens to
// be checked out beside this one — which is the normal case on a developer's
// machine, and never the case in CI, where only this repository exists.
//
// Deliberately not `mkdirSync` here: creating `../pos-api/src/test/resources`
// out of nothing would leave a stray directory next to an unrelated checkout
// and write a file nothing reads.
if (existsSync(dirname(OUT_API))) {
  writeFileSync(OUT_API, serialised, 'utf8');
} else {
  console.log('pos-api is not checked out beside this repository — wrote one copy only.');
}

const count =
  vectors.money.roundMoney.length +
  vectors.money.toPesewas.length +
  vectors.money.fromPesewas.length +
  vectors.money.lineTotal.length +
  vectors.money.sumMoney.length +
  vectors.quantity.roundQuantity.length +
  vectors.weightedAverageCost.cases.length +
  vectors.costPerBaseUnit.cases.length +
  vectors.receiptNumber.cases.length +
  Object.keys(vectors.permissions.roles).length;

console.log(`wrote ${OUT}`);
console.log(`${count} vectors across BR-4, BR-6, BR-11, BR-12 and the §6 permission matrix`);
